use super::{Encode, Encoder};
use crate::error::EncodeError;

macro_rules! impl_tuple {
    ($($name:ident),+ $(,)?) => {
        impl<$($name: Encode),+> Encode for ($($name,)+) {
            #[allow(non_snake_case)]
            fn encode<EN: Encoder>(&self, encoder: &mut EN) -> Result<(), EncodeError> {
                let ($($name,)+) = self;
                $($name.encode(encoder)?;)+
                Ok(())
            }
        }
    };
}

impl_tuple!(A);
impl_tuple!(A, B);
